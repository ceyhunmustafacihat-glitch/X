#!/usr/bin/env python3
"""Prepare the source photos for the William Golding reel.

The photos are small (575x533 and 440x330), so they are upscaled with Lanczos and
gently sharpened. A line sketch of the house is traced from its edges so the house can
"draw itself" before the photo fades in. Everything is embedded as data URLs in
golding/images.js so the canvas can process the pixels without file:// restrictions.

    python3 golding/prep_images.py
"""
import base64
import io
import os

import numpy as np
from PIL import Image, ImageFilter, ImageOps

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "images")


def upscale(im, width):
    h = round(im.height * width / im.width)
    big = im.resize((width, h), Image.LANCZOS)
    return big.filter(ImageFilter.UnsharpMask(radius=2.2, percent=70, threshold=2))


def sketch(im):
    g = ImageOps.grayscale(im).filter(ImageFilter.GaussianBlur(1.6))
    a = np.asarray(g, dtype=np.float32) / 255
    kx = np.array([[-1, 0, 1], [-2, 0, 2], [-1, 0, 1]], dtype=np.float32)
    pad = np.pad(a, 1, mode="edge")
    gx = sum(kx[j, i] * pad[j:j + a.shape[0], i:i + a.shape[1]] for j in range(3) for i in range(3))
    gy = sum(kx.T[j, i] * pad[j:j + a.shape[0], i:i + a.shape[1]] for j in range(3) for i in range(3))
    mag = np.hypot(gx, gy)
    mag /= np.percentile(mag, 99.3) + 1e-6
    alpha = np.clip((mag - 0.18) / 0.5, 0, 1) ** 0.8
    out = np.zeros(a.shape + (4,), dtype=np.uint8)
    out[..., 0], out[..., 1], out[..., 2] = 246, 236, 214
    out[..., 3] = (alpha * 255).astype(np.uint8)
    return Image.fromarray(out, "RGBA")


def data_url(im, fmt, **kw):
    buf = io.BytesIO()
    im.save(buf, fmt, **kw)
    mime = {"JPEG": "image/jpeg", "PNG": "image/png"}[fmt]
    return f"data:{mime};base64," + base64.b64encode(buf.getvalue()).decode()


portrait = upscale(Image.open(os.path.join(SRC, "portre.webp")).convert("RGB"), 1150)
house = upscale(Image.open(os.path.join(SRC, "ev.jpg")).convert("RGB"), 1100)
lines = sketch(house)
with open(os.path.join(HERE, "images.js"), "w", encoding="utf-8") as f:
    f.write("// Generated by golding/prep_images.py — do not edit by hand.\nwindow.IMAGES = {\n")
    f.write(f'  "portrait": "{data_url(portrait, "JPEG", quality=90)}",\n')
    f.write(f'  "house": "{data_url(house, "JPEG", quality=90)}",\n')
    f.write(f'  "houseSketch": "{data_url(lines, "PNG", optimize=True)}"\n')
    f.write("};\n")
print("portrait", portrait.size, "house", house.size)
